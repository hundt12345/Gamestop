#!/usr/bin/env node
/**
 * Refreshes market-data.js with the real GME daily candles.
 *
 * Source: Yahoo Finance chart API (interval 1d, full history since 2019-12).
 * The API returns split-adjusted prices; the archive quotes the prices as they
 * were traded at the time (the event cards talk about "$347.50 on 27 Jan 2021",
 * not about the later 4:1 adjusted value). The script therefore multiplies every
 * bar that predates a split with the split ratio again, so the stored series is
 * "as traded" and matches the contemporaneous record.
 *
 * Usage: node scripts/fetch-market-data.mjs [--symbol GME] [--out market-data.js]
 */

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const START = '2019-12-01';
const HEADERS = {
  'User-Agent': 'Mozilla/5.0 (compatible; gamestop-event-tape/1.0; +https://github.com/hundt12345/Gamestop)',
  Accept: 'application/json'
};

function parseArgs(argv) {
  const options = { symbol: 'GME', out: 'market-data.js' };
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === '--symbol') options.symbol = argv[index + 1];
    if (argv[index] === '--out') options.out = argv[index + 1];
  }
  return options;
}

function isoDate(unixSeconds) {
  return new Date(unixSeconds * 1000).toISOString().slice(0, 10);
}

function round(value, digits) {
  const factor = 10 ** digits;
  return Math.round(value * factor) / factor;
}

async function requestChart(symbol) {
  const url = new URL(`https://query1.finance.yahoo.com/v8/finance/chart/${encodeURIComponent(symbol)}`);
  url.searchParams.set('period1', String(Math.floor(Date.parse(`${START}T00:00:00Z`) / 1000)));
  url.searchParams.set('period2', String(Math.floor(Date.now() / 1000) + 86400));
  url.searchParams.set('interval', '1d');
  url.searchParams.set('events', 'split');
  url.searchParams.set('includePrePost', 'false');

  let lastError = null;
  for (let attempt = 1; attempt <= 3; attempt += 1) {
    try {
      const response = await fetch(url, { headers: HEADERS });
      if (!response.ok) throw new Error(`HTTP ${response.status} ${response.statusText}`);
      const payload = await response.json();
      const result = payload?.chart?.result?.[0];
      if (!result?.timestamp?.length) {
        throw new Error(`no rows returned (${JSON.stringify(payload?.chart?.error ?? null)})`);
      }
      return result;
    } catch (error) {
      lastError = error;
      console.warn(`attempt ${attempt} failed: ${error.message}`);
      await new Promise((resolve) => setTimeout(resolve, attempt * 2500));
    }
  }
  throw lastError;
}

function readSplits(result) {
  const splits = Object.values(result.events?.splits ?? {})
    .map((split) => ({
      date: isoDate(split.date),
      numerator: Number(split.numerator),
      denominator: Number(split.denominator)
    }))
    .filter((split) => Number.isFinite(split.numerator) && split.numerator > 0)
    .sort((a, b) => a.date.localeCompare(b.date));
  return splits;
}

/** Factor that converts a split-adjusted bar back to the price traded that day. */
function tradedFactor(barDate, splits) {
  return splits.reduce((factor, split) => (split.date > barDate ? factor * (split.numerator / split.denominator) : factor), 1);
}

function buildRows(result, splits) {
  const stamps = result.timestamp;
  const quote = result.indicators?.quote?.[0] ?? {};
  const rows = [];

  stamps.forEach((stamp, index) => {
    const open = quote.open?.[index];
    const high = quote.high?.[index];
    const low = quote.low?.[index];
    const close = quote.close?.[index];
    const volume = quote.volume?.[index];
    if (![open, high, low, close].every((value) => Number.isFinite(value))) return;

    const date = isoDate(stamp);
    const factor = tradedFactor(date, splits);
    const bar = {
      date,
      open: round(open * factor, 4),
      high: round(high * factor, 4),
      low: round(low * factor, 4),
      close: round(close * factor, 4),
      volume: Math.round((Number.isFinite(volume) ? volume : 0) / factor)
    };
    if (bar.high < bar.low) [bar.high, bar.low] = [bar.low, bar.high];
    rows.push(bar);
  });

  return rows.sort((a, b) => a.date.localeCompare(b.date));
}

function renderModule({ symbol, rows, splits, updated }) {
  const body = rows.map((row) => `${row.date} ${row.open} ${row.high} ${row.low} ${row.close} ${row.volume}`).join('\n');
  const splitList = splits.length
    ? splits.map((split) => `{ date: '${split.date}', ratio: ${round(split.numerator / split.denominator, 4)} }`).join(', ')
    : '';

  return `// Generated by scripts/fetch-market-data.mjs — do not edit by hand.
// Runs daily OHLCV for ${symbol}, quoted as traded at the time (splits are NOT
// back-applied), so the bars match the prices that were in the tape back then.
// Refresh with: node scripts/fetch-market-data.mjs
window.GME_DAILY = {
  symbol: '${symbol}',
  currency: 'USD',
  source: 'Yahoo Finance chart API / interval 1d',
  asTraded: true,
  updated: '${updated}',
  start: '${rows[0].date}',
  end: '${rows[rows.length - 1].date}',
  splits: [${splitList}],
  rows: \`
${body}
\`
};
`;
}

const options = parseArgs(process.argv.slice(2));
const result = await requestChart(options.symbol);
const splits = readSplits(result);
const rows = buildRows(result, splits);
const updated = new Date().toISOString().slice(0, 10);
const source = renderModule({ symbol: options.symbol, rows, splits, updated });

const target = fileURLToPath(new URL(`../${options.out}`, import.meta.url));
await writeFile(target, source, 'utf8');

const first = rows[0];
const last = rows[rows.length - 1];
const peak = rows.reduce((best, row) => (row.high > best.high ? row : best), rows[0]);
console.log(`${options.symbol}: ${rows.length} daily bars written to ${options.out}`);
console.log(`range     ${first.date} → ${last.date}`);
console.log(`last bar  open ${last.open} / high ${last.high} / low ${last.low} / close ${last.close} / volume ${last.volume}`);
console.log(`peak high ${peak.high} on ${peak.date}`);
if (splits.length) console.log(`splits    ${splits.map((split) => `${split.date} ${split.numerator}:${split.denominator}`).join(', ')}`);
